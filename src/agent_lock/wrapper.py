"""Render the switcher, the Claude wrapper, the Windows cmd, and sudoers.

The scripts bake in the port. They do not read state.json, so agentnet never
sees the controller secret. The Claude wrapper has no `unset` of any name.
"""

from .state import AGENT_USER, CLAUDE_WRAPPER_PATH, SWITCHER_PATH, proxy_url

# Literal names sudo deletes before it execs /bin/sh. No wildcard.
SUDOERS_ENV_DELETE = (
    "LD_PRELOAD",
    "LD_LIBRARY_PATH",
    "LD_AUDIT",
    "LD_DEBUG",
    "LD_DEBUG_OUTPUT",
    "LD_PROFILE",
    "LD_ORIGIN_PATH",
    "DYLD_INSERT_LIBRARIES",
    "DYLD_LIBRARY_PATH",
    "DYLD_FRAMEWORK_PATH",
    "DYLD_FALLBACK_LIBRARY_PATH",
    "DYLD_FALLBACK_FRAMEWORK_PATH",
    "DYLD_IMAGE_SUFFIX",
    "ENV",
    "BASH_ENV",
    "PYTHONPATH",
    "PYTHONHOME",
)


def _no_proxy_block(name):
    """Append localhost, 127.0.0.1, and ::1 only when missing. No helper variables."""
    lines = []
    for host in ("localhost", "127.0.0.1", "::1"):
        lines.append('case ",${%s-}," in' % name)
        lines.append("  *,%s,*) ;;" % host)
        lines.append('  *) %s="${%s:+$%s,}%s" ;;' % (name, name, name, host))
        lines.append("esac")
    lines.append("export %s" % name)
    return "\n".join(lines)


def _git_block():
    return """if [ -z "${GIT_CONFIG_COUNT+x}" ]; then
  GIT_CONFIG_COUNT=1
  GIT_CONFIG_KEY_0=safe.directory
  GIT_CONFIG_VALUE_0='*'
  export GIT_CONFIG_COUNT GIT_CONFIG_KEY_0 GIT_CONFIG_VALUE_0
fi"""


def _proxy_block(port):
    url = proxy_url(port)
    return """HTTP_PROXY=%s
HTTPS_PROXY=$HTTP_PROXY
http_proxy=$HTTP_PROXY
https_proxy=$HTTP_PROXY
export HTTP_PROXY HTTPS_PROXY http_proxy https_proxy
%s
%s""" % (url, _no_proxy_block("NO_PROXY"), _no_proxy_block("no_proxy"))


def _root_exec(runuser_path, darwin):
    if darwin:
        return 'exec /usr/bin/sudo --preserve-env -u %s -- %s "$@"' % (AGENT_USER, SWITCHER_PATH)
    return "exec %s --preserve-environment -u %s -- %s \"$@\"" % (runuser_path, AGENT_USER, SWITCHER_PATH)


def render_switcher(port, runuser_path, darwin=False):
    """POSIX switcher. `runuser_path` is the path found at install time."""
    port = int(port)
    url = proxy_url(port)
    runuser_comment = "" if darwin else (runuser_path or "")
    root_exec = _root_exec(runuser_path or "/usr/sbin/runuser", darwin)
    text = """#!/bin/sh
# Generated by agent-lock. Do not edit.
# wrapper_port=%(port)s
# proxy_url=%(url)s
# claude_wrapper=%(claude)s
# runuser=%(runuser)s
# Keep the caller's PATH across exec. Record it only on the first entry so the
# root hop's safe PATH does not overwrite it.
if [ -z "${AGENT_LOCK_SAVED_PATH+x}" ]; then
  AGENT_LOCK_SAVED_PATH=${PATH-}
  export AGENT_LOCK_SAVED_PATH
fi
PATH=/usr/bin:/bin:/usr/sbin:/sbin
export PATH

if [ "$(/usr/bin/id -un)" = "%(user)s" ]; then
  # An empty snapshot means the owner had the variable unset. Restoring it is
  # not dropping a Claude token. Do not unset the snapshot names.
  if [ -n "${AGENT_LOCK_OWNER_USER+x}" ]; then
    if [ -n "$AGENT_LOCK_OWNER_USER" ]; then
      USER=$AGENT_LOCK_OWNER_USER
      export USER
    else
      unset USER
    fi
  fi
  if [ -n "${AGENT_LOCK_OWNER_LOGNAME+x}" ]; then
    if [ -n "$AGENT_LOCK_OWNER_LOGNAME" ]; then
      LOGNAME=$AGENT_LOCK_OWNER_LOGNAME
      export LOGNAME
    else
      unset LOGNAME
    fi
  fi
  if [ -n "${AGENT_LOCK_OWNER_HOME+x}" ]; then
    if [ -n "$AGENT_LOCK_OWNER_HOME" ]; then
      HOME=$AGENT_LOCK_OWNER_HOME
      export HOME
    else
      unset HOME
    fi
  fi
  PATH=$AGENT_LOCK_SAVED_PATH
  export PATH
  %(proxy)s
  %(git)s
  # Leave ALL_PROXY alone when entering the Claude wrapper. Other commands
  # drop an inherited ALL_PROXY. This tool never sets ALL_PROXY.
  if [ "${1-}" != "%(claude)s" ]; then
    unset ALL_PROXY all_proxy
  fi
  [ "$#" -ge 1 ] || { echo "agent-lock: missing command" >&2; exit 2; }
  exec "$@"
fi

if [ "$(/usr/bin/id -u)" -eq 0 ]; then
  # Command substitution eats the trailing newline. A trailing dot, then
  # stripped, leaves IFS containing space, tab, and newline. Do not export it.
  # sudo's own env_delete already removed the caller's IFS.
  IFS=$(/usr/bin/printf ' \\t\\n.')
  IFS=${IFS%%.}
  unset ENV BASH_ENV PYTHONPATH PYTHONHOME
  AGENT_LOCK_LD_KEYS=$(export -p | /bin/sed -n \\
    's/.*\\(LD_[A-Za-z0-9_][A-Za-z0-9_]*\\|DYLD_[A-Za-z0-9_][A-Za-z0-9_]*\\)=.*/\\1/p')
  # shellcheck disable=SC2086
  for AGENT_LOCK_LD_NAME in $AGENT_LOCK_LD_KEYS; do
    unset "$AGENT_LOCK_LD_NAME"
  done
  unset IFS
  # Do not unset AGENT_LOCK_LD_KEYS or AGENT_LOCK_LD_NAME: they were not
  # exported, so exec drops them. Never exec the user command as root.
  %(root_exec)s
fi

# Not root and not agentnet. Snapshot before the first sudo. After this hop
# USER may be root, so the snapshot has to happen here.
if [ -z "${AGENT_LOCK_OWNER_USER+x}" ]; then
  AGENT_LOCK_OWNER_USER=${USER-}
  AGENT_LOCK_OWNER_LOGNAME=${LOGNAME-}
  AGENT_LOCK_OWNER_HOME=${HOME-}
  export AGENT_LOCK_OWNER_USER AGENT_LOCK_OWNER_LOGNAME AGENT_LOCK_OWNER_HOME
fi
# -l is per command. A passworded ALL rule would make -v prompt every time.
if ! /usr/bin/sudo -n -l %(switcher)s >/dev/null 2>&1; then
  echo "agent-lock: cannot switch to agentnet (sudo -n -l refused)" >&2
  exit 126
fi
exec /usr/bin/sudo -n -E -- %(switcher)s "$@"
""" % {
        "port": port,
        "url": url,
        "claude": CLAUDE_WRAPPER_PATH,
        "runuser": runuser_comment,
        "user": AGENT_USER,
        "proxy": _proxy_block(port),
        "git": _git_block(),
        "root_exec": root_exec,
        "switcher": SWITCHER_PATH,
    }
    return text


def render_claude(port):
    """Claude process wrapper. The body must not contain an unset of any name."""
    port = int(port)
    url = proxy_url(port)
    return """#!/bin/sh
# Generated by agent-lock. Do not edit.
# wrapper_port=%(port)s
# proxy_url=%(url)s
if [ "$(/usr/bin/id -un)" != "%(user)s" ]; then
  exec %(switcher)s %(claude)s "$@"
fi
HTTP_PROXY=%(url)s
HTTPS_PROXY=$HTTP_PROXY
http_proxy=$HTTP_PROXY
https_proxy=$HTTP_PROXY
export HTTP_PROXY HTTPS_PROXY http_proxy https_proxy
%(no_proxy)s
%(no_proxy_lower)s
%(git)s
[ "$#" -ge 1 ] || { echo "agent-lock-claude: missing command" >&2; exit 2; }
exec "$@"
""" % {
        "port": port,
        "url": url,
        "user": AGENT_USER,
        "switcher": SWITCHER_PATH,
        "claude": CLAUDE_WRAPPER_PATH,
        "no_proxy": _no_proxy_block("NO_PROXY"),
        "no_proxy_lower": _no_proxy_block("no_proxy"),
        "git": _git_block(),
    }


def render_sudoers(owner):
    lines = [
        "# agent-lock: passwordless switcher only. The script drops to agentnet.",
        "# !set_logname: otherwise USER and LOGNAME become the target user even when env_reset is off.",
        "# env_delete+= is one literal name per line. No wildcard.",
        "Defaults!%s !env_reset, !set_logname, !set_home, !always_set_home" % SWITCHER_PATH,
    ]
    for name in SUDOERS_ENV_DELETE:
        lines.append('Defaults!%s env_delete+="%s"' % (SWITCHER_PATH, name))
    lines.append("%s ALL=(root) NOPASSWD:SETENV: %s" % (owner, SWITCHER_PATH))
    lines.append("")
    return "\n".join(lines)


def render_windows_cmd(port, sid):
    """SID check and four proxy variables. Does not assign NO_PROXY or store a password."""
    port = int(port)
    url = proxy_url(port)
    return """@echo off
setlocal EnableExtensions
rem Generated by agent-lock. Do not edit.
rem wrapper_port=%(port)s
rem agent_sid=%(sid)s
if "%%~1"=="" (
  echo agent-lock: missing command 1>&2
  exit /b 2
)
set "SID="
for /f "tokens=2 delims=," %%%%S in ('whoami /user /fo csv /nh') do set "SID=%%%%~S"
if /I not "%%SID%%"=="%(sid)s" (
  echo agent-lock: current user is not agentnet. Open a window with: runas /user:agentnet cmd 1>&2
  exit /b 126
)
set "HTTP_PROXY=%(url)s"
set "HTTPS_PROXY=%(url)s"
set "http_proxy=%(url)s"
set "https_proxy=%(url)s"
%%*
exit /b %%ERRORLEVEL%%
""" % {"port": port, "sid": sid, "url": url}
